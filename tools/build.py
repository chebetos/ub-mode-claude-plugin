"""Render the ub-mode plugin skill directory from pinned upstream commits."""

from __future__ import annotations

import json
import os
import re
import shutil
import tempfile
from collections.abc import Callable
from pathlib import Path

from tools.upstream import GitHub, make_fetcher

ROOT = Path(__file__).resolve().parent.parent
SKILL_DIR = ROOT / "plugins/ub-mode/skills/ub-mode"
TEMPLATES = ROOT / "templates"
LOCK = ROOT / "upstream.lock.json"

VENDORED_TOOLS = ("crapper", "dryer", "mutator")
NO_LICENSE = "none published upstream"

TreeFetcher = Callable[[str, str, str], Path]


def _fill(template: str, values: dict[str, str]) -> str:
    """Replace every ``{{key}}`` placeholder in a template.

    Args:
        template: Text containing ``{{key}}`` placeholders.
        values: Placeholder values by key.

    Returns:
        The template with the placeholders replaced.
    """
    for key, value in values.items():
        template = template.replace("{{" + key + "}}", value)
    return template


def render_skill(upstream: str, overlay: str, appendix: str, values: dict[str, str]) -> str:
    """Compose SKILL.md: upstream frontmatter + overlay, upstream body, filled appendix.

    Args:
        upstream: Verbatim upstream SKILL.md.
        overlay: Extra frontmatter lines inserted before the closing fence.
        appendix: Appendix template containing ``{{key}}`` placeholders.
        values: Placeholder values for the appendix.

    Returns:
        The rendered SKILL.md text.
    """
    header, _, body = upstream.removeprefix("---\n").partition("\n---\n")
    return f"---\n{header}\n{overlay.rstrip()}\n---\n{body}\n{_fill(appendix, values)}"


def absolutize_links(markdown: str, repo: str, sha: str) -> str:
    """Rewrite relative Markdown link targets to absolute GitHub URLs.

    Args:
        markdown: Markdown text.
        repo: Repository as ``owner/name``.
        sha: Commit SHA the links should point at.

    Returns:
        Markdown with relative link targets made absolute.
    """

    def rewrite(match: re.Match[str]) -> str:
        target = match.group(2)
        if re.match(r"([a-zA-Z][a-zA-Z0-9+.-]*:|#|/)", target):
            return match.group(0)
        return f"{match.group(1)}(https://github.com/{repo}/blob/{sha}/{target})"

    return re.sub(r"(\[[^\]]*\])\(([^)\s]+)\)", rewrite, markdown)


def render_reference(name: str, readme: str, repo: str, sha: str, license_name: str) -> str:
    """Wrap an upstream README with a provenance header.

    Args:
        name: Upstream name.
        readme: Upstream README text.
        repo: Repository as ``owner/name``.
        sha: Pinned commit SHA.
        license_name: Human-readable license name.

    Returns:
        The reference document.
    """
    header = (
        "<!-- Generated by tools/build.py. Do not edit. -->\n"
        f"> Upstream `{name}` README, pinned.\n"
        f"> Source: https://github.com/{repo}/tree/{sha}\n"
        f"> License: {license_name}\n\n"
    )
    return header + absolutize_links(readme, repo, sha)


def render_launcher(template: str, tool: str, repo: str, sha: str, deps: dict[str, str]) -> str:
    """Fill the launcher template with exact dependency pins.

    Args:
        template: Launcher template with ``{{key}}`` placeholders.
        tool: Tool name.
        repo: Repository as ``owner/name``.
        sha: Pinned commit SHA.
        deps: Mapping of package name to exact version.

    Returns:
        The launcher script text.
    """
    pins = ",\n#   ".join(f'"{name}=={version}"' for name, version in deps.items())
    values = {"dependencies": pins, "tool": tool, "repo": repo, "sha": sha}
    return _fill(template, values)


def _license_name(tree: Path) -> str:
    license_file = tree / "LICENSE"
    if not license_file.is_file():
        return NO_LICENSE
    for line in license_file.read_text().splitlines():
        if line.strip():
            return line.strip()
    return NO_LICENSE


def _vendor_tool(tool: str, tree: Path, vendor: Path) -> None:
    shutil.copytree(
        tree / "src" / tool, vendor / tool, ignore=shutil.ignore_patterns("__pycache__")
    )
    license_file = tree / "LICENSE"
    if license_file.is_file():
        licenses = vendor / "licenses"
        licenses.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(license_file, licenses / tool)


def build(
    lock: dict[str, dict[str, str]], skill_dir: Path, templates: Path, fetch: TreeFetcher
) -> None:
    """Regenerate every generated file under the skill directory.

    Curated files (such as ``references/usage.md``) are left untouched.

    Args:
        lock: Mapping of upstream name to ``repo``, ``ref`` and ``sha``.
        skill_dir: Skill directory to write into.
        templates: Directory holding the build templates.
        fetch: Callable returning a checked-out tree for ``(name, repo, sha)``.
    """
    overlay = (templates / "frontmatter.yaml").read_text()
    appendix = (templates / "skill-appendix.md").read_text()
    launcher = (templates / "launcher.py.tmpl").read_text()
    deps = json.loads((templates / "python-deps.json").read_text())

    trees = {name: fetch(name, pin["repo"], pin["sha"]) for name, pin in lock.items()}

    shutil.rmtree(skill_dir / "scripts", ignore_errors=True)
    shutil.rmtree(skill_dir / "references/upstream", ignore_errors=True)
    (skill_dir / "scripts/vendor").mkdir(parents=True)
    (skill_dir / "references/upstream").mkdir(parents=True)

    upstream_skill = (trees["ub-mode"] / "SKILL.md").read_text()
    values = {"uml_viewer_sha": lock["uml-viewer"]["sha"]}
    (skill_dir / "SKILL.md").write_text(render_skill(upstream_skill, overlay, appendix, values))

    for name, pin in lock.items():
        readme = (trees[name] / "README.md").read_text()
        reference = render_reference(
            name, readme, pin["repo"], pin["sha"], _license_name(trees[name])
        )
        (skill_dir / "references/upstream" / f"{name}.md").write_text(reference)

    for tool in VENDORED_TOOLS:
        pin = lock[tool]
        _vendor_tool(tool, trees[tool], skill_dir / "scripts/vendor")
        script = skill_dir / "scripts" / tool
        script.write_text(render_launcher(launcher, tool, pin["repo"], pin["sha"], deps))
        script.chmod(0o755)


def main() -> None:
    """Build the plugin skill directory from ``upstream.lock.json``."""
    lock = json.loads(LOCK.read_text())
    github = GitHub(make_fetcher(os.environ.get("GITHUB_TOKEN")))
    with tempfile.TemporaryDirectory() as tmp:

        def fetch(name: str, repo: str, sha: str) -> Path:
            return github.extract_tarball(repo, sha, Path(tmp) / name)

        build(lock, SKILL_DIR, TEMPLATES, fetch)


if __name__ == "__main__":
    main()

from pathlib import Path

import pytest

from tools.build import (
    absolutize_links,
    build,
    render_launcher,
    render_reference,
    render_skill,
)

UPSTREAM_SKILL = """---
name: ub-mode
description: >
  Follow the principles.
---

# ub-mode

Body line.
"""

OVERLAY = "disable-model-invocation: true\nallowed-tools: Read\n"
APPENDIX = "## Tools in this plugin\n\numl {{uml_viewer_sha}}\n"


def test_render_skill_keeps_upstream_frontmatter_and_body_verbatim():
    out = render_skill(UPSTREAM_SKILL, OVERLAY, APPENDIX, {"uml_viewer_sha": "deadbeef"})
    assert out.startswith("---\nname: ub-mode\ndescription: >\n  Follow the principles.\n")
    assert "# ub-mode\n\nBody line.\n" in out


def test_render_skill_inserts_overlay_before_closing_fence():
    out = render_skill(UPSTREAM_SKILL, OVERLAY, APPENDIX, {"uml_viewer_sha": "x"})
    header = out.split("\n---\n")[0]
    assert header.endswith("disable-model-invocation: true\nallowed-tools: Read")


def test_render_skill_appends_filled_appendix_after_body():
    out = render_skill(UPSTREAM_SKILL, OVERLAY, APPENDIX, {"uml_viewer_sha": "deadbeef"})
    assert out.endswith("Body line.\n\n## Tools in this plugin\n\numl deadbeef\n")


def test_absolutize_links_rewrites_relative_but_not_absolute_or_anchor():
    md = "[a](docs/x.md) [b](https://e.com/y) [c](#top) [d](mailto:a@b.c)"
    assert absolutize_links(md, "o/r", "abc") == (
        "[a](https://github.com/o/r/blob/abc/docs/x.md) "
        "[b](https://e.com/y) [c](#top) [d](mailto:a@b.c)"
    )


def test_render_reference_prefixes_provenance_header():
    out = render_reference("crapper", "# Crapper\n", "unclebob/crapper", "abc", "BSD Zero Clause")
    assert out.startswith("<!-- Generated by tools/build.py. Do not edit. -->\n")
    assert "Source: https://github.com/unclebob/crapper/tree/abc" in out
    assert "License: BSD Zero Clause" in out
    assert out.endswith("# Crapper\n")


def test_render_launcher_pins_dependencies_and_names_tool():
    template = "# deps: {{dependencies}}\n# tool: {{tool}} {{repo}}@{{sha}}\n"
    out = render_launcher(template, "crapper", "unclebob/crapper", "abc", {"tree-sitter": "0.26.0"})
    assert out == '# deps: "tree-sitter==0.26.0"\n# tool: crapper unclebob/crapper@abc\n'


def _fake_tree(base: Path, name: str, readme: str, license_line: str | None) -> Path:
    root = base / name
    (root / "src" / name).mkdir(parents=True)
    (root / "src" / name / "__main__.py").write_text(f"print('{name}')\n")
    (root / "README.md").write_text(readme)
    if license_line:
        (root / "LICENSE").write_text(f"{license_line}\n\nText\n")
    return root


def _setup(tmp_path: Path) -> tuple[dict, Path, Path, Path]:
    trees = tmp_path / "trees"
    (trees / "ub-mode").mkdir(parents=True)
    (trees / "ub-mode" / "SKILL.md").write_text(UPSTREAM_SKILL)
    (trees / "ub-mode" / "README.md").write_text("# ub\n[x](a.md)\n")
    for name in ("crapper", "dryer", "mutator"):
        _fake_tree(trees, name, f"# {name}\n", "BSD Zero Clause License")
    (trees / "uml-viewer").mkdir()
    (trees / "uml-viewer" / "README.md").write_text("# uml\n")
    lock = {
        n: {"repo": f"unclebob/{n}", "ref": "master", "sha": f"sha-{n}"}
        for n in ("ub-mode", "crapper", "dryer", "mutator", "uml-viewer")
    }
    templates = tmp_path / "templates"
    templates.mkdir()
    (templates / "frontmatter.yaml").write_text(OVERLAY)
    (templates / "skill-appendix.md").write_text(APPENDIX)
    (templates / "launcher.py.tmpl").write_text("#!shebang\n# {{dependencies}}\n# {{tool}}\n")
    (templates / "python-deps.json").write_text('{"tree-sitter": "0.26.0"}')
    return lock, trees, templates, tmp_path / "skill"


def _run(tmp_path: Path) -> Path:
    lock, trees, templates, skill = _setup(tmp_path)
    build(lock, skill, templates, lambda name, repo, sha: trees / name)
    return skill


def test_build_writes_rendered_skill_md(tmp_path: Path):
    skill = _run(tmp_path)
    text = (skill / "SKILL.md").read_text()
    assert "disable-model-invocation: true" in text
    assert "uml sha-uml-viewer" in text


def test_build_vendors_tool_packages_flat_with_licenses(tmp_path: Path):
    skill = _run(tmp_path)
    assert (skill / "scripts/vendor/crapper/__main__.py").read_text() == "print('crapper')\n"
    assert (skill / "scripts/vendor/licenses/crapper").read_text().startswith("BSD Zero Clause")


def test_build_generates_executable_launchers(tmp_path: Path):
    skill = _run(tmp_path)
    launcher = skill / "scripts/mutator"
    assert launcher.read_text().startswith("#!shebang\n")
    assert launcher.stat().st_mode & 0o111


def test_build_writes_upstream_references_for_every_upstream(tmp_path: Path):
    skill = _run(tmp_path)
    refs = sorted(p.name for p in (skill / "references/upstream").iterdir())
    assert refs == ["crapper.md", "dryer.md", "mutator.md", "ub-mode.md", "uml-viewer.md"]
    ub = (skill / "references/upstream/ub-mode.md").read_text()
    assert "https://github.com/unclebob/ub-mode/blob/sha-ub-mode/a.md" in ub


def test_build_is_idempotent_and_preserves_curated_files(tmp_path: Path):
    lock, trees, templates, skill = _setup(tmp_path)
    fetch = lambda name, repo, sha: trees / name  # noqa: E731
    build(lock, skill, templates, fetch)
    (skill / "references/usage.md").write_text("curated")
    (skill / "scripts/vendor/stale.py").write_text("old")
    first = {p: p.read_bytes() for p in skill.rglob("*") if p.is_file() and p.name != "stale.py"}
    build(lock, skill, templates, fetch)
    second = {p: p.read_bytes() for p in skill.rglob("*") if p.is_file()}
    assert first == second
    assert (skill / "references/usage.md").read_text() == "curated"


def test_build_keeps_generated_files_when_a_fetch_fails(tmp_path: Path):
    lock, trees, templates, skill = _setup(tmp_path)
    build(lock, skill, templates, lambda name, repo, sha: trees / name)
    before = {p: p.read_bytes() for p in skill.rglob("*") if p.is_file()}

    def failing(name: str, repo: str, sha: str) -> Path:
        if name == "mutator":
            raise RuntimeError("download failed")
        return trees / name

    with pytest.raises(RuntimeError):
        build(lock, skill, templates, failing)
    assert {p: p.read_bytes() for p in skill.rglob("*") if p.is_file()} == before
